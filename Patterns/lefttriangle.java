class Main {
    public static void main(String[] args) {
        
        int n = 5;
        
        for(int i = 1; i <= n; i++)
        {
            for(int j=1 ; j<= i ; j++)  // where j is less than i there * will be printed....
            {
              
              System.out.print("*" + " ");
               
                   
            }
            System.out.println();
        
        }
    }
}